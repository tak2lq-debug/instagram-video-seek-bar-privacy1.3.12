(() => {
  'use strict';

  // v1.3.2: controls are tied to the actually visible portion of their media,
  // not to an off-screen or recycled Instagram DOM node.
  const DEFAULT_SETTINGS = { thin: 3, thick: 8, color: '#ffffff', opacity: 96, thumb: 'circle' };
  const ALLOWED_MEDIA_PROTOCOLS = new Set(['https:', 'blob:']);
  const OVERLAY_CLASS = 'igseek-overlay';
  const RANGE_CLASS = 'igseek-range';
  const SVG_NS = 'http://www.w3.org/2000/svg';
  const CLIPPED_OVERFLOW = new Set(['hidden', 'scroll', 'auto', 'clip']);

  function clampNumber(value, min, max, fallback) {
    const number = Number(value);
    return Number.isFinite(number) ? Math.min(max, Math.max(min, number)) : fallback;
  }

  function sanitizeSettings(values = {}) {
    return {
      thin: Math.round(clampNumber(values.thin, 2, 10, DEFAULT_SETTINGS.thin)),
      thick: Math.round(clampNumber(values.thick, 4, 16, DEFAULT_SETTINGS.thick)),
      color: typeof values.color === 'string' && /^#[0-9a-f]{6}$/i.test(values.color)
        ? values.color : DEFAULT_SETTINGS.color,
      opacity: Math.round(clampNumber(values.opacity, 30, 100, DEFAULT_SETTINGS.opacity)),
      thumb: values.thumb === 'none' ? 'none' : 'circle'
    };
  }

  function getSafeMediaUrl(value) {
    if (typeof value !== 'string' || !value) return null;
    try {
      const url = new URL(value, location.href);
      // Blob URLs generated by the page are same-origin, unlike arbitrary blob URLs.
      if (url.protocol === 'blob:' && url.origin !== location.origin) return null;
      return ALLOWED_MEDIA_PROTOCOLS.has(url.protocol) ? url.href : null;
    } catch (_) {
      return null;
    }
  }

  function icon(name) {
    const svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', '22');
    svg.setAttribute('height', '22');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.setAttribute('aria-hidden', 'true');
    const shapes = name === 'zoom' ? [
      ['circle', { cx: '10.8', cy: '10.8', r: '7.7' }],
      ['path', { d: 'm16.5 16.5 4.5 4.5' }],
      ['path', { d: 'M10.8 7.4v6.8M7.4 10.8h6.8' }]
    ] : [
      ['path', { d: 'M14.4 4H9.6L7.4 7H4a2 2 0 0 0-2 2v9a2 2 0 0 0 2 2h16a2 2 0 0 0 2-2V9a2 2 0 0 0-2-2h-3.4L14.4 4Z' }],
      ['circle', { cx: '12', cy: '13', r: '3.2' }]
    ];
    for (const [tag, attributes] of shapes) {
      const part = document.createElementNS(SVG_NS, tag);
      for (const [key, value] of Object.entries(attributes)) part.setAttribute(key, value);
      svg.appendChild(part);
    }
    return svg;
  }

  // A single UI root prevents scanning our own preview <video> or lightbox <img>.
  const uiRoot = document.createElement('div');
  uiRoot.className = 'igseek-root';
  document.documentElement.appendChild(uiRoot);

  function ensureRoot() {
    if (!uiRoot.isConnected) document.documentElement.appendChild(uiRoot);
  }

  const attached = new WeakMap();
  const records = new Set();
  const imageButtons = new Map();
  const watchedImages = new WeakSet();
  const trackedImages = new Set();
  let settings = { ...DEFAULT_SETTINGS };
  let pending = false;
  let previewBox = null;
  let activePreview = null;
  let lightbox = null;
  let toastBox = null;
  let toastTimer = null;

  function applySeekSettings(record) {
    const overlay = record.overlay;
    overlay.style.setProperty('--igseek-thin', `${settings.thin}px`);
    overlay.style.setProperty('--igseek-thick', `${Math.max(settings.thin, settings.thick)}px`);
    overlay.style.setProperty('--igseek-color', settings.color);
    overlay.style.setProperty('--igseek-alpha', String(settings.opacity / 100));
    overlay.dataset.thumb = settings.thumb;
  }

  if (typeof chrome !== 'undefined' && chrome.storage?.local) {
    chrome.storage.local.get(DEFAULT_SETTINGS, values => {
      if (chrome.runtime.lastError) return;
      settings = sanitizeSettings({ ...DEFAULT_SETTINGS, ...values });
      for (const record of records) applySeekSettings(record);
    });
    chrome.storage.onChanged.addListener((changes, area) => {
      if (area !== 'local') return;
      const next = { ...settings };
      for (const key of Object.keys(DEFAULT_SETTINGS)) {
        if (changes[key]) next[key] = changes[key].newValue;
      }
      settings = sanitizeSettings(next);
      for (const record of records) applySeekSettings(record);
    });
  }

  function notify(message) {
    ensureRoot();
    if (!toastBox?.isConnected) {
      toastBox = document.createElement('div');
      toastBox.className = 'igseek-toast';
      uiRoot.appendChild(toastBox);
    }
    toastBox.textContent = message;
    toastBox.classList.add('is-visible');
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => toastBox?.classList.remove('is-visible'), 4200);
  }

  function screenshot(video) {
    if (!video.videoWidth || !video.videoHeight || video.readyState < 2) {
      notify('映像を読み込んでからお試しください');
      return;
    }
    try {
      video.pause();
      const canvas = document.createElement('canvas');
      canvas.width = video.videoWidth;
      canvas.height = video.videoHeight;
      const context = canvas.getContext('2d', { alpha: false });
      if (!context) { notify('この動画は保存できませんでした'); return; }
      context.drawImage(video, 0, 0);
      canvas.toBlob(blob => {
        if (!blob) { notify('この動画は保存できませんでした'); return; }
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `instagram-frame-${Math.floor(video.currentTime * 1000)}ms.png`;
        uiRoot.appendChild(a);
        a.click();
        a.remove();
        setTimeout(() => URL.revokeObjectURL(url), 30000);
        notify('映像フレームをPNGで保存しました');
      }, 'image/png');
    } catch (_) {
      notify('この動画はブラウザの保護により直接保存できません。Edgeのスクリーンショット機能をご利用ください。');
    }
  }

  // Intersect video/image with both viewport AND scrolling/overflow-clipped parents.
  function visibleBounds(element, minWidth, minHeight) {
    if (!element.isConnected || uiRoot.contains(element)) return null;
    if (typeof element.checkVisibility === 'function' &&
        !element.checkVisibility({ checkOpacity: true, checkVisibilityCSS: true })) return null;
    const full = element.getBoundingClientRect();
    if (full.width < minWidth || full.height < minHeight) return null;
    const rect = {
      left: Math.max(0, full.left), top: Math.max(0, full.top),
      right: Math.min(innerWidth, full.right), bottom: Math.min(innerHeight, full.bottom)
    };
    for (let parent = element.parentElement; parent && parent !== document.documentElement; parent = parent.parentElement) {
      const style = getComputedStyle(parent);
      if (style.visibility === 'hidden' || style.display === 'none' || Number(style.opacity) === 0) return null;
      const clipsX = CLIPPED_OVERFLOW.has(style.overflowX);
      const clipsY = CLIPPED_OVERFLOW.has(style.overflowY);
      if (!clipsX && !clipsY) continue;
      const clip = parent.getBoundingClientRect();
      if (clipsX) {
        rect.left = Math.max(rect.left, clip.left);
        rect.right = Math.min(rect.right, clip.right);
      }
      if (clipsY) {
        rect.top = Math.max(rect.top, clip.top);
        rect.bottom = Math.min(rect.bottom, clip.bottom);
      }
    }
    rect.width = rect.right - rect.left;
    rect.height = rect.bottom - rect.top;
    if (rect.width < Math.max(64, Math.min(160, full.width * 0.25)) ||
        rect.height < Math.max(48, Math.min(110, full.height * 0.25))) return null;
    return rect;
  }

  function activeDialog() {
    // Instagram's modal viewer normally has role=dialog. Ignore hidden dialogs.
    const candidates = document.querySelectorAll('dialog[open], [role="dialog"], [aria-modal="true"]');
    for (let i = candidates.length - 1; i >= 0; i--) {
      const dialog = candidates[i];
      const box = dialog.getBoundingClientRect();
      if (box.width >= 160 && box.height >= 120 && box.right > 0 && box.bottom > 0 &&
          box.left < innerWidth && box.top < innerHeight &&
          dialog.checkVisibility?.({ checkOpacity: true })) return dialog;
    }
    return null;
  }

  function notOccluded(element, bounds, dialog) {
    if (dialog && !dialog.contains(element)) return false;
    // Sample several points. If a different modal/large overlay sits above the
    // media, fixed-position extension controls must not leak through it.
    const host = element.parentElement?.parentElement || element.parentElement;
    let sawOwnMedia = false;
    let blockingCover = false;
    for (const [fx, fy] of [[.5, .5], [.25, .3], [.75, .7], [.5, .82]]) {
      const x = Math.round(bounds.left + bounds.width * fx);
      const y = Math.round(bounds.top + bounds.height * fy);
      const top = document.elementsFromPoint(x, y).find(node => !uiRoot.contains(node));
      if (!top) continue;
      if (top === element || element.contains(top) || host?.contains(top)) {
        sawOwnMedia = true;
        break;
      }
      // A full-screen overlay (even one without role=dialog) can obscure it.
      for (let node = top; node && node !== document.documentElement; node = node.parentElement) {
        const s = getComputedStyle(node);
        if (s.position !== 'fixed') continue;
        const r = node.getBoundingClientRect();
        if (r.width >= innerWidth * 0.65 && r.height >= innerHeight * 0.65) {
          blockingCover = true;
          break;
        }
      }
    }
    return sawOwnMedia || !blockingCover;
  }

  function updateWideMode() {
    const narrow = innerWidth >= 280 && innerWidth <= 690;
    const enabledParents = new Set();
    for (const record of records) {
      const video = record.video;
      if (!video.isConnected) continue;
      const parent = video.parentElement;
      if (!parent) continue;
      const rect = parent.getBoundingClientRect();
      const suitable = narrow && rect.width >= 180 && rect.width <= innerWidth + 5 &&
        rect.height >= 180 && rect.height <= innerHeight * 1.4;
      if (suitable) enabledParents.add(parent);
      if (video.classList.contains('igseek-narrow-video') !== suitable) {
        video.classList.toggle('igseek-narrow-video', suitable);
      }
      record.narrowParent = parent;
    }
    for (const record of records) {
      if (record.narrowParent) {
        const should = enabledParents.has(record.narrowParent);
        if (record.narrowParent.classList.contains('igseek-narrow-frame') !== should) {
          record.narrowParent.classList.toggle('igseek-narrow-frame', should);
        }
      }
    }
  }

  function ensurePreview() {
    ensureRoot();
    if (previewBox?.isConnected) return previewBox;
    const box = document.createElement('div');
    box.className = 'igseek-preview';
    const video = document.createElement('video');
    video.muted = true;
    video.playsInline = true;
    video.preload = 'metadata';
    const time = document.createElement('div');
    time.className = 'igseek-preview-time';
    box.append(video, time);
    uiRoot.appendChild(box);
    previewBox = box;
    return box;
  }

  function showPreview(video, time, range) {
    const source = getSafeMediaUrl(video.currentSrc || video.src);
    if (!source) { hidePreview(); return; }
    const box = ensurePreview();
    const previewVideo = box.querySelector('video');
    const previewTime = box.querySelector('.igseek-preview-time');
    if (!previewVideo || !previewTime) return;
    if (previewVideo.dataset.source !== source) {
      previewVideo.pause();
      previewVideo.removeAttribute('src');
      previewVideo.src = source;
      previewVideo.dataset.source = source;
      previewVideo.load();
    }
    const setFrame = () => {
      if (Number.isFinite(previewVideo.duration) && previewVideo.duration > 0) {
        try { previewVideo.currentTime = Math.min(time, Math.max(0, previewVideo.duration - .05)); } catch (_) {}
      }
    };
    if (previewVideo.readyState >= 1) setFrame();
    else previewVideo.addEventListener('loadedmetadata', setFrame, { once: true });
    const minutes = Math.floor(time / 60);
    const seconds = Math.floor(time % 60).toString().padStart(2, '0');
    previewTime.textContent = `${minutes}:${seconds}`;
    const rect = range.getBoundingClientRect();
    box.style.left = `${Math.max(8, Math.min(innerWidth - 168, rect.left + rect.width * (time / video.duration) - 80))}px`;
    box.style.top = `${Math.max(8, rect.top - 116)}px`;
    box.classList.add('is-visible');
    activePreview = box;
  }

  function hidePreview() {
    if (activePreview) activePreview.classList.remove('is-visible');
    activePreview = null;
  }

  function updateProgress(record) {
    const { video, range, overlay } = record;
    if (overlay.classList.contains('is-dragging')) return;
    if (!Number.isFinite(video.duration) || video.duration <= 0) return;
    const progress = Math.min(1000, Math.max(0, (video.currentTime / video.duration) * 1000));
    range.value = String(progress);
    range.style.setProperty('--igseek-progress', `${progress / 10}%`);
  }

  function detach(record) {
    record.controller.abort();
    record.overlay.remove();
    if (record.narrowParent && record.narrowParent.isConnected) {
      record.narrowParent.classList.remove('igseek-narrow-frame');
    }
    record.video.classList.remove('igseek-narrow-video');
    records.delete(record);
    attached.delete(record.video);
    hidePreview();
  }

  function attach(video) {
    if (!(video instanceof HTMLVideoElement) || uiRoot.contains(video) || attached.has(video)) return;
    ensureRoot();
    const overlay = document.createElement('div');
    overlay.className = OVERLAY_CLASS;
    overlay.hidden = true; // CSS [hidden] uses !important; never override with display:flex.
    overlay.setAttribute('aria-label', '動画のシークバー');
    const range = document.createElement('input');
    range.className = RANGE_CLASS;
    range.type = 'range';
    range.min = '0';
    range.max = '1000';
    range.step = '1';
    range.value = '0';
    range.setAttribute('aria-label', '動画の再生位置');
    range.title = 'ドラッグして再生位置を変更';

    const camera = document.createElement('button');
    camera.type = 'button';
    camera.className = 'igseek-camera';
    camera.appendChild(icon('camera'));
    camera.title = '現在のフレームをPNGで保存';
    camera.setAttribute('aria-label', '動画のスクリーンショットを保存');
    overlay.append(range, camera);
    uiRoot.appendChild(overlay);

    const controller = new AbortController();
    const record = { video, overlay, range, camera, controller, narrowParent: null };
    attached.set(video, record);
    records.add(record);
    applySeekSettings(record);
    const opts = { signal: controller.signal };
    for (const name of ['pointerdown', 'pointerup', 'mousedown', 'mouseup', 'click', 'dblclick', 'touchstart', 'touchend']) {
      overlay.addEventListener(name, event => event.stopPropagation(), opts);
    }
    range.addEventListener('pointerdown', event => {
      overlay.classList.add('is-dragging');
      event.stopPropagation();
      if (Number.isFinite(video.duration) && video.duration > 0) {
        showPreview(video, Number(range.value) / 1000 * video.duration, range);
      }
    }, opts);
    range.addEventListener('input', event => {
      event.stopPropagation();
      if (Number.isFinite(video.duration) && video.duration > 0) {
        const time = Number(range.value) / 1000 * video.duration;
        try { video.currentTime = time; } catch (_) {}
        range.style.setProperty('--igseek-progress', `${Number(range.value) / 10}%`);
        if (overlay.classList.contains('is-dragging')) showPreview(video, time, range);
      }
    }, opts);
    const stopDrag = () => { overlay.classList.remove('is-dragging'); hidePreview(); };
    for (const name of ['lostpointercapture', 'pointerup', 'pointercancel', 'change']) {
      range.addEventListener(name, stopDrag, opts);
    }
    camera.addEventListener('click', event => {
      event.preventDefault();
      event.stopPropagation();
      screenshot(video);
    }, opts);
    for (const name of ['timeupdate', 'seeking', 'seeked']) {
      video.addEventListener(name, () => updateProgress(record), { passive: true, signal: controller.signal });
    }
    for (const name of ['loadedmetadata', 'durationchange', 'loadeddata', 'play', 'pause', 'resize']) {
      video.addEventListener(name, scheduleUpdate, { passive: true, signal: controller.signal });
    }
    scheduleUpdate();
  }

  function ensureLightbox() {
    ensureRoot();
    if (lightbox?.isConnected) return lightbox;
    const box = document.createElement('div');
    box.className = 'igseek-lightbox';
    const toolbar = document.createElement('div');
    toolbar.className = 'igseek-lightbox-toolbar';
    const openTab = document.createElement('button');
    openTab.type = 'button';
    openTab.className = 'igseek-open-tab';
    openTab.textContent = '新しいタブで開く';
    const close = document.createElement('button');
    close.type = 'button';
    close.className = 'igseek-close';
    close.setAttribute('aria-label', '閉じる');
    close.textContent = '×';
    const image = document.createElement('img');
    image.alt = '拡大画像';
    toolbar.append(openTab, close);
    box.append(toolbar, image);
    box.addEventListener('click', event => {
      if (event.target === box || event.target.closest('.igseek-close')) closeLightbox();
    });
    openTab.addEventListener('click', () => {
      const src = getSafeMediaUrl(image.src);
      if (src) window.open(src, '_blank', 'noopener,noreferrer');
      else notify('安全でない形式のURLは開けません');
    });
    uiRoot.appendChild(box);
    lightbox = box;
    return box;
  }

  function openLightbox(value) {
    const src = getSafeMediaUrl(value);
    if (!src) { notify('安全でない形式の画像URLは開けません'); return; }
    const box = ensureLightbox();
    box.querySelector('img').src = src;
    box.classList.add('is-visible');
    document.addEventListener('keydown', onEscape);
    hidePreview();
    scheduleUpdate();
  }

  function closeLightbox() {
    if (lightbox) lightbox.classList.remove('is-visible');
    document.removeEventListener('keydown', onEscape);
    scheduleUpdate();
  }

  function onEscape(event) {
    if (event.key === 'Escape') closeLightbox();
  }

  function watchImage(img) {
    if (!(img instanceof HTMLImageElement) || uiRoot.contains(img)) return;
    trackedImages.add(img);
    if (!watchedImages.has(img)) {
      watchedImages.add(img);
      img.addEventListener('load', scheduleUpdate, { passive: true });
    }
    // Natural size may not be available until load; updateImages will decide eligibility.
  }

  function ensureImageButton(img) {
    if (imageButtons.has(img)) return imageButtons.get(img);
    const button = document.createElement('button');
    button.className = 'igseek-image-zoom';
    button.type = 'button';
    button.hidden = true;
    button.appendChild(icon('zoom'));
    button.title = '画像を拡大表示';
    button.setAttribute('aria-label', '画像を拡大表示');
    button.addEventListener('click', event => {
      event.preventDefault();
      event.stopPropagation();
      openLightbox(img.currentSrc || img.src);
    });
    uiRoot.appendChild(button);
    imageButtons.set(img, button);
    return button;
  }

  function scanNode(node) {
    if (!(node instanceof Element) || node === uiRoot || uiRoot.contains(node)) return;
    if (node instanceof HTMLVideoElement) attach(node);
    else if (node instanceof HTMLImageElement) watchImage(node);
    for (const video of node.querySelectorAll('video')) attach(video);
    for (const img of node.querySelectorAll('img')) watchImage(img);
  }

  function overlap(a, b) {
    const width = Math.max(0, Math.min(a.right, b.right) - Math.max(a.left, b.left));
    const height = Math.max(0, Math.min(a.bottom, b.bottom) - Math.max(a.top, b.top));
    if (!width || !height) return 0;
    return width * height / Math.min(a.width * a.height, b.width * b.height);
  }

  function updateImages(dialog) {
    // Image candidates are collected lazily, so thumbnails and avatars never get buttons.
    const seen = [];
    for (const img of trackedImages) {
      if (!img.isConnected || uiRoot.contains(img)) {
        trackedImages.delete(img);
        const oldButton = imageButtons.get(img);
        if (oldButton) { oldButton.remove(); imageButtons.delete(img); }
        continue;
      }
      const bounds = visibleBounds(img, 250, 180);
      const sizeOk = img.naturalWidth >= 350 && img.naturalHeight >= 180;
      if (!bounds || !sizeOk || bounds.width < 220 || bounds.height < 170 ||
          !notOccluded(img, bounds, dialog)) {
        const button = imageButtons.get(img);
        if (button) button.hidden = true;
        continue;
      }
      // Ignore duplicate or background images in the same screen area.
      if (seen.some(other => overlap(bounds, other) > 0.75)) {
        const button = imageButtons.get(img);
        if (button) button.hidden = true;
        continue;
      }
      seen.push(bounds);
      const button = ensureImageButton(img);
      button.hidden = !!(lightbox?.classList.contains('is-visible'));
      button.style.left = `${Math.round(bounds.right - 37)}px`;
      button.style.top = `${Math.round(bounds.top + 8)}px`;
    }
    for (const [img, button] of imageButtons) {
      if (!img.isConnected) {
        button.remove();
        imageButtons.delete(img);
      } else if (uiRoot.contains(img)) {
        button.remove();
        imageButtons.delete(img);
      }
    }
  }

  function updateAll() {
    ensureRoot();
    updateWideMode();
    const dialog = activeDialog();
    const visible = [];
    const lightboxOpen = !!lightbox?.classList.contains('is-visible');
    for (const record of Array.from(records)) {
      if (!record.video.isConnected) { detach(record); continue; }
      updateProgress(record);
      const bounds = visibleBounds(record.video, 100, 70);
      const usable = !lightboxOpen && bounds && record.video.duration > 0 &&
        Number.isFinite(record.video.duration) && notOccluded(record.video, bounds, dialog);
      record.overlay.hidden = !usable;
      if (usable) visible.push({ record, bounds, score: (record.video.paused ? 0 : 1000) + bounds.width * bounds.height / 5000 });
    }
    // Some Instagram carousels retain overlapping old media elements: one bar per visual area.
    visible.sort((a, b) => b.score - a.score);
    const kept = [];
    for (const { record, bounds } of visible) {
      if (kept.some(previous => overlap(bounds, previous) > .70)) {
        record.overlay.hidden = true;
        continue;
      }
      kept.push(bounds);
      const inset = Math.min(8, Math.max(0, bounds.width * .015));
      record.overlay.style.left = `${Math.round(bounds.left + inset)}px`;
      record.overlay.style.top = `${Math.round(bounds.bottom - 14)}px`;
      record.overlay.style.width = `${Math.round(bounds.width - inset * 2)}px`;
    }
    updateImages(dialog);
  }

  function scheduleUpdate() {
    if (pending) return;
    pending = true;
    requestAnimationFrame(() => {
      pending = false;
      updateAll();
    });
  }

  // Initial scan and incremental mutation tracking: own UI children are skipped.
  document.querySelectorAll('video').forEach(attach);
  document.querySelectorAll('img').forEach(watchImage);
  scheduleUpdate();
  const observer = new MutationObserver(mutations => {
    let changesPage = false;
    for (const mutation of mutations) {
      if (uiRoot.contains(mutation.target)) continue;
      if (mutation.type === 'attributes') {
        changesPage = true;
        continue;
      }
      for (const node of mutation.addedNodes) {
        if (node === uiRoot || uiRoot.contains(node)) continue;
        scanNode(node);
        changesPage = true;
      }
      if (mutation.removedNodes.length) changesPage = true;
    }
    if (changesPage) scheduleUpdate();
  });
  observer.observe(document.documentElement, {
    childList: true, subtree: true, attributes: true,
    attributeFilter: ['class', 'style', 'hidden', 'aria-hidden', 'open']
  });
  // Capture catches scroll events in Instagram's nested scrolling containers.
  document.addEventListener('scroll', scheduleUpdate, { capture: true, passive: true });
  window.addEventListener('scroll', scheduleUpdate, { passive: true });
  window.addEventListener('resize', scheduleUpdate, { passive: true });
  window.addEventListener('orientationchange', scheduleUpdate, { passive: true });
  window.addEventListener('pointerup', hidePreview, { passive: true });
})();
